BEGIN;

-- Verificar que estamos en la base correcta y que el login se conserva.
DO $check$
BEGIN
  IF current_database() <> 'postgres' THEN
    RAISE EXCEPTION 'Base incorrecta: %. Se esperaba postgres.', current_database();
  END IF;
  IF to_regnamespace('erp') IS NULL THEN
    RAISE EXCEPTION 'No existe el esquema erp.';
  END IF;
  IF to_regclass('erp.users') IS NULL
     OR to_regclass('erp.auth_access_tokens') IS NULL
     OR to_regclass('erp.adonis_schema') IS NULL
     OR to_regclass('erp.adonis_schema_versions') IS NULL THEN
    RAISE EXCEPTION 'Falta alguna tabla del sistema. Operacion cancelada para proteger el login.';
  END IF;
END;
$check$;

-- 1. Proveedores
CREATE TABLE erp.suppliers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  business_name VARCHAR(150) NOT NULL,
  trade_name VARCHAR(150),
  document_type VARCHAR(20),
  document_number VARCHAR(20) UNIQUE,
  contact_name VARCHAR(120),
  phone VARCHAR(20),
  email VARCHAR(150),
  address TEXT,
  notes TEXT,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. Categorias
CREATE TABLE erp.product_categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL UNIQUE,
  description TEXT,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. Productos / stock actual / precio de venta FIJO MANUAL
CREATE TABLE erp.products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id BIGINT REFERENCES erp.product_categories(id) ON DELETE RESTRICT,
  code VARCHAR(50) NOT NULL UNIQUE,
  barcode VARCHAR(100) UNIQUE,
  name VARCHAR(150) NOT NULL,
  description TEXT,
  brand VARCHAR(100),
  model VARCHAR(100),
  unit VARCHAR(30) NOT NULL DEFAULT 'UNIDAD',
  sale_price NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (sale_price >= 0),
  stock INTEGER NOT NULL DEFAULT 0 CHECK (stock >= 0),
  minimum_stock INTEGER NOT NULL DEFAULT 0 CHECK (minimum_stock >= 0),
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 4. Imagenes de productos
CREATE TABLE erp.product_images (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id BIGINT NOT NULL REFERENCES erp.products(id) ON DELETE RESTRICT,
  image_url TEXT NOT NULL,
  alt_text VARCHAR(200),
  is_primary BOOLEAN NOT NULL DEFAULT FALSE,
  sort_order INTEGER NOT NULL DEFAULT 0 CHECK (sort_order >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 5. Catalogo de cada proveedor: un producto puede tener varios proveedores
CREATE TABLE erp.supplier_products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  supplier_id BIGINT NOT NULL REFERENCES erp.suppliers(id) ON DELETE RESTRICT,
  product_id BIGINT NOT NULL REFERENCES erp.products(id) ON DELETE RESTRICT,
  supplier_sku VARCHAR(100),
  reference_cost NUMERIC(12,2) CHECK (reference_cost >= 0),
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_supplier_products UNIQUE (supplier_id, product_id),
  CONSTRAINT uq_supplier_products_id_product UNIQUE (id, product_id)
);

-- 6. Compras: RECEPCION es lo que aumenta el stock
CREATE TABLE erp.purchases (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  purchase_number VARCHAR(50) NOT NULL UNIQUE,
  supplier_id BIGINT NOT NULL REFERENCES erp.suppliers(id) ON DELETE RESTRICT,
  document_type VARCHAR(30),
  document_number VARCHAR(50),
  purchase_date TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  received_at TIMESTAMPTZ,
  subtotal NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (subtotal >= 0),
  tax_amount NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (tax_amount >= 0),
  total NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (total >= 0),
  status VARCHAR(20) NOT NULL DEFAULT 'BORRADOR'
    CHECK (status IN ('BORRADOR', 'RECIBIDA', 'ANULADA')),
  notes TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT ck_purchases_received_date
    CHECK (status <> 'RECIBIDA' OR received_at IS NOT NULL)
);

-- 7. Lineas de compra: costo historico, NO cambia products.sale_price
CREATE TABLE erp.purchase_details (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  purchase_id BIGINT NOT NULL REFERENCES erp.purchases(id) ON DELETE RESTRICT,
  product_id BIGINT NOT NULL REFERENCES erp.products(id) ON DELETE RESTRICT,
  supplier_product_id BIGINT NOT NULL,
  quantity INTEGER NOT NULL CHECK (quantity > 0),
  unit_cost NUMERIC(12,2) NOT NULL CHECK (unit_cost >= 0),
  subtotal NUMERIC(12,2) NOT NULL CHECK (subtotal >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT fk_purchase_detail_supplier_product
    FOREIGN KEY (supplier_product_id, product_id)
    REFERENCES erp.supplier_products(id, product_id) ON DELETE RESTRICT,
  CONSTRAINT ck_purchase_detail_subtotal
    CHECK (subtotal = ROUND(quantity * unit_cost, 2))
);

-- 8. Historial de movimientos del inventario
CREATE TABLE erp.stock_movements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id BIGINT NOT NULL REFERENCES erp.products(id) ON DELETE RESTRICT,
  movement_type VARCHAR(20) NOT NULL
    CHECK (movement_type IN ('ENTRADA', 'SALIDA', 'AJUSTE')),
  reference_type VARCHAR(30) NOT NULL
    CHECK (reference_type IN ('COMPRA', 'VENTA', 'AJUSTE')),
  reference_id BIGINT,
  quantity_change INTEGER NOT NULL CHECK (quantity_change <> 0),
  stock_before INTEGER NOT NULL CHECK (stock_before >= 0),
  stock_after INTEGER NOT NULL CHECK (stock_after >= 0),
  reason TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT ck_stock_change_math
    CHECK (stock_after = stock_before + quantity_change),
  CONSTRAINT ck_stock_change_direction
    CHECK (
      movement_type = 'AJUSTE'
      OR (movement_type = 'ENTRADA' AND quantity_change > 0)
      OR (movement_type = 'SALIDA' AND quantity_change < 0)
    )
);

-- 9. Clientes (opcionales en una venta POS)
CREATE TABLE erp.customers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  document_type VARCHAR(20),
  document_number VARCHAR(20) UNIQUE,
  name VARCHAR(150) NOT NULL,
  phone VARCHAR(20),
  email VARCHAR(150),
  address TEXT,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 10. Ventas y descuento fijo en soles por venta
CREATE TABLE erp.sales (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sale_number VARCHAR(50) NOT NULL UNIQUE,
  customer_id BIGINT REFERENCES erp.customers(id) ON DELETE RESTRICT,
  sale_date TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  subtotal NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (subtotal >= 0),
  discount_amount NUMERIC(12,2) NOT NULL DEFAULT 0
    CHECK (discount_amount >= 0),
  tax_amount NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (tax_amount >= 0),
  total NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (total >= 0),
  status VARCHAR(20) NOT NULL DEFAULT 'COMPLETADA'
    CHECK (status IN ('COMPLETADA', 'ANULADA')),
  notes TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT ck_sale_discount CHECK (discount_amount <= subtotal),
  CONSTRAINT ck_sale_total CHECK (total = subtotal - discount_amount),
  CONSTRAINT ck_sale_tax CHECK (tax_amount <= total)
);

-- 11. Detalle historico de cada venta
CREATE TABLE erp.sale_details (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sale_id BIGINT NOT NULL REFERENCES erp.sales(id) ON DELETE RESTRICT,
  product_id BIGINT NOT NULL REFERENCES erp.products(id) ON DELETE RESTRICT,
  product_code VARCHAR(50) NOT NULL,
  product_name VARCHAR(150) NOT NULL,
  quantity INTEGER NOT NULL CHECK (quantity > 0),
  unit_price NUMERIC(12,2) NOT NULL CHECK (unit_price >= 0),
  subtotal NUMERIC(12,2) NOT NULL CHECK (subtotal >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT ck_sale_detail_subtotal
    CHECK (subtotal = ROUND(quantity * unit_price, 2))
);

-- 12. Pagos (admite varios por venta)
CREATE TABLE erp.payments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sale_id BIGINT NOT NULL REFERENCES erp.sales(id) ON DELETE RESTRICT,
  payment_method VARCHAR(30) NOT NULL
    CHECK (payment_method IN ('EFECTIVO', 'YAPE', 'PLIN', 'TARJETA', 'TRANSFERENCIA')),
  amount NUMERIC(12,2) NOT NULL CHECK (amount >= 0),
  amount_received NUMERIC(12,2) CHECK (amount_received >= 0),
  change_amount NUMERIC(12,2) CHECK (change_amount >= 0),
  reference_number VARCHAR(100),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Las columnas de usuario se crean con el TIPO REAL de erp.users.id.
-- De esta forma funciona tanto si el ID original es INTEGER como BIGINT.
DO $user_fk$
DECLARE
  user_id_type TEXT;
BEGIN
  SELECT format_type(a.atttypid, a.atttypmod)
    INTO user_id_type
  FROM pg_attribute a
  WHERE a.attrelid = 'erp.users'::regclass
    AND a.attname = 'id'
    AND a.attnum > 0
    AND NOT a.attisdropped;

  IF user_id_type IS NULL THEN
    RAISE EXCEPTION 'No se encontro la columna erp.users.id';
  END IF;

  EXECUTE format(
    'ALTER TABLE erp.purchases ADD COLUMN user_id %s NOT NULL REFERENCES erp.users(id) ON DELETE RESTRICT',
    user_id_type
  );
  EXECUTE format(
    'ALTER TABLE erp.sales ADD COLUMN user_id %s NOT NULL REFERENCES erp.users(id) ON DELETE RESTRICT',
    user_id_type
  );
  EXECUTE format(
    'ALTER TABLE erp.stock_movements ADD COLUMN user_id %s REFERENCES erp.users(id) ON DELETE RESTRICT',
    user_id_type
  );
END;
$user_fk$;

-- Indices para busqueda, relaciones y filtros por periodo.
CREATE INDEX idx_products_name ON erp.products (name);
CREATE INDEX idx_products_brand ON erp.products (brand);
CREATE INDEX idx_products_category ON erp.products (category_id);
CREATE INDEX idx_supplier_products_product ON erp.supplier_products (product_id);
CREATE INDEX idx_product_images_product ON erp.product_images (product_id);
CREATE UNIQUE INDEX uq_product_primary_image
  ON erp.product_images (product_id) WHERE is_primary = TRUE;
CREATE INDEX idx_purchases_supplier_date
  ON erp.purchases (supplier_id, purchase_date DESC);
CREATE INDEX idx_purchases_user ON erp.purchases (user_id);
CREATE INDEX idx_purchase_details_purchase ON erp.purchase_details (purchase_id);
CREATE INDEX idx_purchase_details_product ON erp.purchase_details (product_id);
CREATE INDEX idx_purchase_details_supplier_product
  ON erp.purchase_details (supplier_product_id);
CREATE INDEX idx_stock_movements_product_date
  ON erp.stock_movements (product_id, created_at DESC);
CREATE INDEX idx_stock_movements_user ON erp.stock_movements (user_id);
CREATE INDEX idx_sales_date ON erp.sales (sale_date DESC);
CREATE INDEX idx_sales_customer ON erp.sales (customer_id);
CREATE INDEX idx_sales_user ON erp.sales (user_id);
CREATE INDEX idx_sale_details_sale ON erp.sale_details (sale_id);
CREATE INDEX idx_sale_details_product ON erp.sale_details (product_id);
CREATE INDEX idx_payments_sale ON erp.payments (sale_id);

COMMIT;

